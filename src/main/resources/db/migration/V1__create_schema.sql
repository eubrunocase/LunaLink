-- Tabela users (SINGLE_TABLE inheritance com DTYPE)
CREATE TABLE public.users (
    id uuid NOT NULL,
    dtype character varying(31) NOT NULL DEFAULT 'USER',
    apartment character varying(255),
    email character varying(255) NOT NULL,
    name character varying(255) NOT NULL,
    password character varying(255) NOT NULL,
    role character varying(255) NOT NULL,
    token_version integer NOT NULL DEFAULT 0,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- Tabela space
CREATE TABLE public.space (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.space_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    type character varying(255),
    CONSTRAINT space_pkey PRIMARY KEY (id),
    CONSTRAINT space_type_check CHECK (((type)::text = ANY ((ARRAY['SALAO_FESTAS'::character varying, 'CHURRASQUEIRA'::character varying, 'ACADEMIA'::character varying, 'CAMPO_FUTEBOL'::character varying])::text[])))
);

-- Tabela reservation
CREATE TABLE public.reservation (
    id uuid NOT NULL,
    date date NOT NULL,
    status character varying(255),
    notes text,
    created_at timestamp(6) without time zone,
    canceled_at timestamp(6) without time zone,
    user_id uuid NOT NULL,
    space_id bigint NOT NULL,
    CONSTRAINT reservation_pkey PRIMARY KEY (id),
    CONSTRAINT uk_user_date_space UNIQUE (user_id, date, space_id),
    CONSTRAINT fk_reservation_user FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_reservation_space FOREIGN KEY (space_id) REFERENCES public.space(id)
);

-- Tabela equipment
CREATE TABLE public.equipment (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.equipment_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    name character varying(255) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT equipment_pkey PRIMARY KEY (id),
    CONSTRAINT equipment_name_key UNIQUE (name)
);

-- Tabela guest
CREATE TABLE public.guest (
    id uuid NOT NULL,
    name character varying(255) NOT NULL,
    checked_in boolean NOT NULL DEFAULT false,
    checked_in_at timestamp(6) without time zone,
    reservation_id uuid NOT NULL,
    CONSTRAINT guest_pkey PRIMARY KEY (id),
    CONSTRAINT fk_guest_reservation FOREIGN KEY (reservation_id) REFERENCES public.reservation(id)
);

-- Tabela liability_term
CREATE TABLE public.liability_term (
    id uuid NOT NULL,
    content text NOT NULL,
    signed_by_resident boolean NOT NULL DEFAULT false,
    signed_at timestamp(6) without time zone,
    reservation_id uuid NOT NULL,
    CONSTRAINT liability_term_pkey PRIMARY KEY (id),
    CONSTRAINT uk_liability_term_reservation UNIQUE (reservation_id),
    CONSTRAINT fk_liability_term_reservation FOREIGN KEY (reservation_id) REFERENCES public.reservation(id)
);

-- Tabela delivery
CREATE TABLE public.delivery (
    id uuid NOT NULL,
    user_id uuid NOT NULL,
    protocol_number character varying(255),
    discrimination character varying(255),
    created_at timestamp(6) without time zone NOT NULL,
    created_by character varying(255) NOT NULL,
    voucher_key character varying(255) NOT NULL,
    other_recipient character varying(255),
    status character varying(255) NOT NULL,
    delivered_at timestamp(6) without time zone,
    picked_up_by character varying(255),
    CONSTRAINT delivery_pkey PRIMARY KEY (id)
